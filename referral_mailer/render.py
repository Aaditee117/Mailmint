"""Template loading and per-person rendering."""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from string import Formatter

from .people import Person

PLACEHOLDERS = [
    "first_name", "last_name", "full_name", "company",
    "role", "job_id", "notes", "sender_name",
]


class TemplateError(RuntimeError):
    pass


@dataclass
class Template:
    subject: str
    body: str

    @property
    def fields_used(self) -> set[str]:
        found = set()
        for text in (self.subject, self.body):
            found |= {f for _, f, _, _ in Formatter().parse(text) if f}
        return found


def load_template(path: Path) -> Template:
    if not path.exists():
        raise TemplateError(f"template not found: {path}")

    lines = path.read_text(encoding="utf-8").splitlines()
    kept = [ln for ln in lines if not ln.lstrip().startswith("#")]

    subject = ""
    body_start = 0
    for index, line in enumerate(kept):
        if not line.strip():
            continue
        if not line.lower().startswith("subject:"):
            raise TemplateError(
                f"{path}: the first non-comment line must start with 'Subject:' "
                f"(found: {line[:60]!r})"
            )
        subject = line.split(":", 1)[1].strip()
        body_start = index + 1
        break

    if not subject:
        raise TemplateError(f"{path}: subject line is empty")

    body = "\n".join(kept[body_start:]).strip("\n")
    if not body.strip():
        raise TemplateError(f"{path}: body is empty")

    unknown = {
        f for _, f, _, _ in Formatter().parse(subject + body) if f
    } - set(PLACEHOLDERS)
    if unknown:
        bad = ", ".join("{" + name + "}" for name in sorted(unknown))
        available = ", ".join("{" + name + "}" for name in PLACEHOLDERS)
        raise TemplateError(
            f"{path}: unknown placeholder(s) {bad}. Available: {available}"
        )

    return Template(subject=subject, body=body.rstrip() + "\n")


def humanise(text: str) -> str:
    """Capitalise only tokens that carry no casing information of their own.

    A CSV written by hand or generated by a model often has "priya nair", and
    "Hi priya," is not a greeting anyone should send. Tokens that already have
    internal capitals - McDonald, O'Neill - are left exactly as written, since
    those are deliberate and title-casing would damage them.
    """
    parts = []
    for token in (text or "").split():
        parts.append(token.capitalize() if token == token.lower() else token)
    return " ".join(parts)


def context_for(person: Person, sender_name: str) -> dict[str, str]:
    return {
        "first_name": humanise(person.first or person.name.first),
        "last_name": humanise(person.last or person.name.last),
        "full_name": humanise(person.display_name),
        "company": person.company,
        "role": person.role,
        "job_id": person.job_id,
        "notes": person.notes,
        "sender_name": sender_name,
    }


def render(template: Template, person: Person, sender_name: str) -> tuple[str, str]:
    """Return (subject, body) for one person."""
    context = context_for(person, sender_name)
    try:
        subject = template.subject.format(**context)
        body = template.body.format(**context)
    except KeyError as exc:
        raise TemplateError(f"template uses unknown placeholder {exc}") from exc
    except (IndexError, ValueError) as exc:
        raise TemplateError(
            f"template has a malformed brace - to write a literal brace, double "
            f"it as {{{{ or }}}} ({exc})"
        ) from exc

    # A stray "()" or a doubled space is what an unfilled placeholder looks like
    # to the recipient. Tidy the artefacts rather than shipping them - but only
    # collapse runs that follow visible text, so deliberate indentation in the
    # body survives.
    subject = _tidy(subject).strip(" -–—")
    body = "\n".join(_tidy(line) for line in body.split("\n"))
    return subject, body


def _tidy(text: str) -> str:
    text = re.sub(r"\(\s*\)", "", text)
    text = re.sub(r"(?<=\S)[ \t]{2,}", " ", text)
    return text.rstrip()


def empty_placeholders(template: Template, person: Person, sender_name: str) -> list[str]:
    """Placeholders the template uses but this person has no value for."""
    context = context_for(person, sender_name)
    return sorted(f for f in template.fields_used if not context.get(f, "").strip())
